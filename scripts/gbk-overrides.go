//go:build ignore

// Run from the repository root after npx tsx scripts/gbk-fixtures.ts.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"golang.org/x/text/encoding/simplifiedchinese"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	body, e := os.ReadFile("testdata/gbk-parity.json")
	must(e)
	var values map[string]string
	must(json.Unmarshal(body, &values))
	keys := []string{}
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var output strings.Builder
	output.WriteString("// Code generated by scripts/gbk-overrides.go from the pinned upstream TextDecoder; DO NOT EDIT.\npackage gbk\nvar overrides=map[uint16]string{\n")
	n := 0
	for _, key := range keys {
		value, e := strconv.ParseUint(key, 16, 16)
		must(e)
		data := []byte{byte(value)}
		if len(key) > 2 {
			data = []byte{byte(value >> 8), byte(value)}
		}
		got, e := simplifiedchinese.GBK.NewDecoder().Bytes(data)
		must(e)
		if string(got) != values[key] {
			fmt.Fprintf(&output, "0x%s:%q,\n", key, values[key])
			n++
		}
	}
	output.WriteString("}\n")
	code, e := format.Source([]byte(output.String()))
	must(e)
	must(os.WriteFile("internal/gbk/overrides.go", code, 0644))
	fmt.Printf("Generated %d Windows-936 mapping overrides\n", n)
}
func must(e error) {
	if e != nil {
		panic(e)
	}
}
